#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const raw = JSON.parse(fs.readFileSync('docs/strategy/refactor/_env-inventory-raw.json', 'utf8'));
const { stats, env } = raw;

const byProcess = new Map();
for (const e of env) {
  for (const proc of e.processes) {
    if (!byProcess.has(proc)) byProcess.set(proc, []);
    byProcess.get(proc).push(e);
  }
}

const ordered = [...byProcess.keys()].sort();
const lines = [];
lines.push('# ENV inventory — solana-alpha — 2026-05-20');
lines.push('');
lines.push('Generated by `scripts-tmp/env-inventory.mjs` from `ecosystem.config.cjs`.');
lines.push('Verified against TS/JS source (src/, scripts/, scripts-tmp/) for actual reads.');
lines.push('');
lines.push('## Stats');
lines.push('');
lines.push(`- Total unique env keys: **${stats.total}**`);
lines.push(`- Orphan (declared, never read in code): **${stats.orphans}**`);
lines.push(`- Multi-value (same key, different values across processes): **${stats.multiValue}**`);
lines.push(`- Multi-process (same key + same value in ≥2 processes): **${stats.multiProcess}**`);
lines.push(`- Active (read by ≥1 file): **${stats.ok}**`);
lines.push('');
lines.push('## ORPHAN candidates (safe-to-remove unless something missing)');
lines.push('');
lines.push('Each entry: declared in `ecosystem.config.cjs`, exported by .sh wrapper if any,');
lines.push('but **no `process.env.<KEY>` read in any .ts/.mjs/.js file**.');
lines.push('');
lines.push('| Key | Process | Value | Note |');
lines.push('|-----|---------|-------|------|');
for (const e of env.filter((x) => x.status === 'ORPHAN')) {
  lines.push(`| \`${e.key}\` | ${e.processes.join(', ')} | ${e.valueSample} | candidate for removal |`);
}
lines.push('');
lines.push('## Per-process count');
lines.push('');
lines.push('| Process | Total env keys | Orphans | Multi-process shared |');
lines.push('|---------|----------------|---------|----------------------|');
for (const proc of ordered) {
  const items = byProcess.get(proc);
  const orphCount = items.filter((x) => x.status === 'ORPHAN').length;
  const sharedCount = items.filter((x) => x.status === 'MULTI_PROCESS').length;
  lines.push(`| ${proc} | ${items.length} | ${orphCount} | ${sharedCount} |`);
}
lines.push('');
lines.push('## Heaviest groups');
lines.push('');

const groups = {};
for (const e of env) {
  let g = 'OTHER';
  if (e.key.startsWith('PAPER_LIVE_STAGED_ENTRY_')) g = 'PAPER_LIVE_STAGED_ENTRY_*';
  else if (e.key.startsWith('PAPER_DCA_')) g = 'PAPER_DCA_*';
  else if (e.key.startsWith('PAPER_DIP_')) g = 'PAPER_DIP_*';
  else if (e.key.startsWith('PAPER_WAVE_B_') || e.key.startsWith('WAVE_B_')) g = 'WAVE_B_*';
  else if (e.key.startsWith('PAPER_PRIORITY_FEE_')) g = 'PAPER_PRIORITY_FEE_*';
  else if (e.key.startsWith('PAPER_SAFETY_')) g = 'PAPER_SAFETY_*';
  else if (e.key.startsWith('PAPER_HOLDERS_') || e.key.startsWith('PAPER_HOLDER_')) g = 'PAPER_HOLDERS_*';
  else if (e.key.startsWith('PAPER_TELEGRAM_') || e.key.startsWith('TELEGRAM_')) g = 'TELEGRAM_*';
  else if (e.key.startsWith('PAPER_KILL_') || e.key.startsWith('PAPER_STOP_')) g = 'PAPER_KILL/STOP_*';
  else if (e.key.startsWith('PAPER_MIN_') || e.key.startsWith('PAPER_MAX_')) g = 'PAPER_MIN/MAX_*';
  else if (e.key.startsWith('PAPER_TP_') || e.key.startsWith('PAPER_TAKE_')) g = 'PAPER_TP/TAKE_*';
  else if (e.key.startsWith('PAPER_TRAIL_')) g = 'PAPER_TRAIL_*';
  else if (e.key.startsWith('PAPER_REENTRY_') || e.key.startsWith('PAPER_RE_ENTRY_')) g = 'PAPER_REENTRY_*';
  else if (e.key.startsWith('PAPER_VOL_') || e.key.startsWith('PAPER_VOLUME_')) g = 'PAPER_VOLUME_*';
  else if (e.key.startsWith('PAPER_BTC_')) g = 'PAPER_BTC_*';
  else if (e.key.startsWith('PAPER_DENY') || e.key.startsWith('PAPER_BLOCK')) g = 'PAPER_DENY/BLOCK_*';
  else if (e.key.startsWith('PAPER_FIRST_PROBE_') || e.key.startsWith('LIVE_FIRST_PROBE_')) g = 'FIRST_PROBE_*';
  else if (e.key.startsWith('LIVE_MINT_WHITELIST') || e.key.startsWith('LIVE_OSCAR_WHITELIST')) g = 'LIVE_WHITELIST_*';
  else if (e.key.startsWith('LIVE_')) g = 'LIVE_*';
  else if (e.key.startsWith('PAPER_')) g = 'PAPER_OTHER';
  else if (e.key.startsWith('SPIKE_')) g = 'SPIKE_*';
  else if (e.key.startsWith('PULLBACK_')) g = 'PULLBACK_*';
  else if (e.key.startsWith('RETRACE_')) g = 'RETRACE_*';
  else if (e.key.startsWith('SA_')) g = 'SA_*';
  else if (e.key.startsWith('JUPITER_')) g = 'JUPITER_*';
  else if (e.key.startsWith('PG_') || e.key.startsWith('DATABASE_')) g = 'DATABASE_*';
  groups[g] = (groups[g] || 0) + 1;
}
const sortedGroups = Object.entries(groups).sort((a, b) => b[1] - a[1]);
lines.push('| Group | Count |');
lines.push('|-------|-------|');
for (const [g, n] of sortedGroups) lines.push(`| ${g} | ${n} |`);
lines.push('');
lines.push('## Methodology and limits');
lines.push('');
lines.push('- Detection of "read in code" = substring search for the env key in .ts/.mjs/.js/.cjs files.');
lines.push('- This catches both `process.env.KEY` and indirect reads via `process.env[name]`,');
lines.push('  but **misses** computed names like `process.env[`KEY_${SUFFIX}`]`. Such cases are extremely rare.');
lines.push('- Files in `data/`, `archive/`, `node_modules/`, `.git/` excluded.');
lines.push('- `.sh` wrappers in `scripts/` only **export** env, they are not "readers".');
lines.push('- Raw JSON: `_env-inventory-raw.json` (in this folder).');
lines.push('');
lines.push('## Next step (Refactor 3/4)');
lines.push('');
lines.push('Proposed step 4: remove the 3 ORPHAN keys from `ecosystem.config.cjs`,');
lines.push('one process at a time, atomic deploys per NORM §5. After that — pick the');
lines.push('heaviest group (likely `PAPER_LIVE_STAGED_ENTRY_*` or `PAPER_DIP_*`)');
lines.push('and review which keys are still relevant vs. legacy from earlier experiments.');

fs.writeFileSync('docs/strategy/refactor/ENV_INVENTORY.md', lines.join('\n') + '\n');
console.log('wrote docs/strategy/refactor/ENV_INVENTORY.md', lines.length, 'lines');
